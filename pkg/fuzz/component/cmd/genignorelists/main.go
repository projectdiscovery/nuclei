package main

import (
	"bytes"
	"embed"
	"flag"
	"fmt"
	"go/format"
	"net/http"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"text/template"

	wappalyzer "github.com/projectdiscovery/wappalyzergo"
)

//go:embed seed_headers.txt seed_cookies.txt
var seedFS embed.FS

const fileTemplate = `// Code generated by genignorelists; DO NOT EDIT.
// Run: go run ./pkg/fuzz/component/cmd/genignorelists
// or:  make fuzz-ignorelists
// Optional: -wappalyzer merges cookie/header names from wappalyzergo fingerprints.

package component

// defaultIgnoredHeaderKeys lists headers that must not be fuzzed.
var defaultIgnoredHeaderKeys = map[string]struct{}{
{{- range .Headers}}
	{{printf "%q" .}}: {},
{{- end}}
}

// defaultIgnoredCookieKeys lists cookies that must not be fuzzed, in lowercase.
var defaultIgnoredCookieKeys = map[string]struct{}{
{{- range .Cookies}}
	{{printf "%q" .}}: {},
{{- end}}
}

// defaultIgnoredCookiePrefixes holds cookie patterns ending in "*" (from the seed or -wappalyzer), in lowercase.
var defaultIgnoredCookiePrefixes = []string{
{{- range .CookiePrefixes}}
	{{printf "%q" .}},
{{- end}}
}
`

func main() {
	out := flag.String("out", "", "output Go file (default: ignorelists.gen.go in the component package)")
	withWappalyzer := flag.Bool("wappalyzer", false, "merge header/cookie names from wappalyzergo fingerprints")
	flag.Parse()

	outPath := *out
	if outPath == "" {
		outPath = defaultOutPath()
		if outPath == "" {
			fatalf("could not resolve generator path")
		}
	}

	seedHeaders, err := readSeedLines("seed_headers.txt")
	if err != nil {
		fatalf("seed headers: %v", err)
	}
	seedCookies, err := readSeedLines("seed_cookies.txt")
	if err != nil {
		fatalf("seed cookies: %v", err)
	}

	headers := map[string]struct{}{}
	for _, h := range seedHeaders {
		headers[http.CanonicalHeaderKey(h)] = struct{}{}
	}
	cookies := map[string]struct{}{}
	cookiePrefixes := map[string]struct{}{}
	// sessionCookies counts the names dropped by the session cookie rule
	var sessionCookies int
	for _, c := range seedCookies {
		if isSessionCookie(c) {
			sessionCookies++
			continue
		}
		addCookieIgnore(cookies, cookiePrefixes, c)
	}

	var fromWappalyzerHeaders, fromWappalyzerCookies int
	if *withWappalyzer {
		wa, err := wappalyzer.New()
		if err != nil {
			fatalf("wappalyzer: %v", err)
		}
		fps := wa.GetFingerprints()
		if fps == nil || fps.Apps == nil {
			fatalf("wappalyzer: empty fingerprints")
		}
		for _, app := range fps.Apps {
			if app == nil {
				continue
			}
			for name := range app.Headers {
				name = strings.TrimSpace(name)
				if name == "" {
					continue
				}
				canon := http.CanonicalHeaderKey(name)
				if canon == "Set-Cookie" {
					continue
				}
				if _, ok := headers[canon]; !ok {
					fromWappalyzerHeaders++
				}
				headers[canon] = struct{}{}
			}
			for name := range app.Cookies {
				if isSessionCookie(name) {
					sessionCookies++
					continue
				}
				beforeCookies, beforePrefixes := len(cookies), len(cookiePrefixes)
				addCookieIgnore(cookies, cookiePrefixes, name)
				if len(cookies) > beforeCookies || len(cookiePrefixes) > beforePrefixes {
					fromWappalyzerCookies++
				}
			}
		}
	}

	headerList := sortedKeys(headers)
	cookieList := sortedKeys(cookies)
	prefixList := sortedKeys(cookiePrefixes)
	sort.Slice(prefixList, func(i, j int) bool {
		if len(prefixList[i]) == len(prefixList[j]) {
			return prefixList[i] < prefixList[j]
		}
		return len(prefixList[i]) > len(prefixList[j])
	})

	var buf bytes.Buffer
	tpl := template.Must(template.New("gen").Parse(fileTemplate))
	if err := tpl.Execute(&buf, map[string][]string{
		"Headers":        headerList,
		"Cookies":        cookieList,
		"CookiePrefixes": prefixList,
	}); err != nil {
		fatalf("template: %v", err)
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		fatalf("format: %v", err)
	}

	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		fatalf("write %s: %v", outPath, err)
	}

	fmt.Fprintf(os.Stderr, "wrote %s\n", outPath)
	fmt.Fprintf(os.Stderr, "headers: %d (seed %d", len(headerList), len(seedHeaders))
	if *withWappalyzer {
		fmt.Fprintf(os.Stderr, ", +%d wappalyzer", fromWappalyzerHeaders)
	}
	fmt.Fprintf(os.Stderr, ")\n")
	fmt.Fprintf(os.Stderr, "cookies: %d exact, %d prefixes (seed %d", len(cookieList), len(prefixList), len(seedCookies))
	if *withWappalyzer {
		fmt.Fprintf(os.Stderr, ", +%d wappalyzer", fromWappalyzerCookies)
	}
	fmt.Fprintf(os.Stderr, ")\n")
	fmt.Fprintf(os.Stderr, "session cookies kept fuzzable: %d\n", sessionCookies)
}

// sessionCookieTokens mark cookie names that carry a session, a login or a
// CSRF token. Such cookies are real fuzz targets, so they never go in the
// ignore list, even when a seed or a wappalyzer fingerprint names them.
var sessionCookieTokens = []string{
	"session", "sess", "sid", "auth", "token", "csrf", "xsrf", "jwt",
	"login", "logged_in", "signin", "remember", "saml", "sso", "oidc",
	"member", "admin", "account", "customer",
}

// sessionCookieNames are session and auth cookies the token rule misses.
// A trailing * makes the entry a prefix match.
// Most are the default session cookie names of web frameworks and CMSes.
var sessionCookieNames = []string{
	"cfid",
	"cfglobals",
	"wordpress_*",
	"wp-postpass_*",
	"cakephp",
	"phpbb*",
	"frontend",
	"concrete5",
	"prestashop*",
	"dokuwiki",
	"pyrocms",
	"impresscms",
	"episerver",
	"collectiveaccess",
	"jtlshop",
	"dynamicweb",
	"moodleid_*",
	"ushahidi",
	"merchello",
	"opengrok",
	"e107*",
	"publiccms_user",
	"_jumpcloud_user_console_*",
}

// isSessionCookie reports whether a cookie name (or a name pattern ending in
// "*") belongs to a session or auth cookie. The match ignores case.
func isSessionCookie(name string) bool {
	name = strings.ToLower(strings.TrimSuffix(strings.TrimSpace(name), "*"))
	if name == "" {
		return false
	}
	for _, token := range sessionCookieTokens {
		if strings.Contains(name, token) {
			return true
		}
	}
	for _, known := range sessionCookieNames {
		if prefix, ok := strings.CutSuffix(known, "*"); ok {
			if strings.HasPrefix(name, prefix) {
				return true
			}
			continue
		}
		if name == known {
			return true
		}
	}
	return false
}

func readSeedLines(name string) ([]string, error) {
	bin, err := seedFS.ReadFile(name)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, line := range strings.Split(string(bin), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		out = append(out, line)
	}
	return out, nil
}

func addCookieIgnore(exact, prefixes map[string]struct{}, name string) {
	name = strings.TrimSpace(name)
	if name == "" {
		return
	}
	if strings.HasSuffix(name, "*") {
		prefix := strings.TrimSuffix(name, "*")
		if isCookieToken(prefix) {
			prefixes[strings.ToLower(prefix)] = struct{}{}
		}
		return
	}
	if isCookieToken(name) {
		exact[strings.ToLower(name)] = struct{}{}
	}
}

// isCookieToken reports whether name is a valid RFC 6265 cookie name.
// wappalyzergo cookie keys can hold regex fragments such as "(?i)ltpatoken".
func isCookieToken(name string) bool {
	if name == "" {
		return false
	}
	for _, r := range name {
		if r <= ' ' || r >= 0x7f || strings.ContainsRune("()<>@,;:\\\"/[]?={}*", r) {
			return false
		}
	}
	return true
}

func sortedKeys(m map[string]struct{}) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// defaultOutPath returns the ignorelists.gen.go path in the component package, two levels above this tool.
func defaultOutPath() string {
	_, file, _, _ := runtime.Caller(0)
	wd, _ := os.Getwd()
	return outPathFrom(file, wd)
}

// outPathFrom uses the source file path when it is absolute. Under -trimpath it is module-relative, so the module root is found from wd instead.
func outPathFrom(file, wd string) string {
	if filepath.IsAbs(file) {
		return filepath.Join(filepath.Dir(file), "..", "..", "ignorelists.gen.go")
	}
	for dir := wd; dir != ""; {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return filepath.Join(dir, "pkg", "fuzz", "component", "ignorelists.gen.go")
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	return ""
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
